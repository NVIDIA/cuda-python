from __future__ import annotations

import sys
import types
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "cuda_python" / "docs" / "exts"))
import release_date

PAGE = """.. Generated by release_notes; do not edit or commit.

Package 1.0.0
=============

New Features
------------

- First entry.
"""


def _read(monkeypatch, docname, text, project="cuda.core", date="2026-03-06"):
    monkeypatch.setattr(release_date, "_git_tag_date", lambda _tag: date)
    source = [text]
    release_date._on_source_read(types.SimpleNamespace(config=types.SimpleNamespace(project=project)), docname, source)
    return source[0]


@pytest.mark.agent_authored(model="claude-sonnet-5-5")
def test_date_is_added_after_the_title(monkeypatch):
    result = _read(monkeypatch, "release/1.0.0-notes", PAGE)
    assert "Package 1.0.0\n=============\n\nReleased on Mar 6, 2026\n\nNew Features\n" in result


@pytest.mark.agent_authored(model="claude-sonnet-5-5")
def test_words_released_on_elsewhere_in_the_page_do_not_suppress_the_date(monkeypatch):
    text = PAGE + "\n- The feature was released on Tuesday.\n- Released on request.\n"
    result = _read(monkeypatch, "release/1.0.0-notes", text)
    assert "\nReleased on Mar 6, 2026\n" in result


@pytest.mark.agent_authored(model="claude-sonnet-5-5")
@pytest.mark.parametrize("existing", ["Released on Jan 1, 2026", "released on Jan 1, 2026"])
def test_an_existing_date_line_after_the_title_is_kept(monkeypatch, existing):
    text = PAGE.replace("=============\n\n", f"=============\n\n{existing}\n\n", 1)
    assert _read(monkeypatch, "release/1.0.0-notes", text) == text


@pytest.mark.agent_authored(model="claude-sonnet-5-5")
def test_other_pages_unknown_projects_and_untagged_versions_are_left_alone(monkeypatch):
    assert _read(monkeypatch, "install", PAGE) == PAGE
    assert _read(monkeypatch, "release/1.0.0-notes", PAGE, project="Not A Project") == PAGE
    assert _read(monkeypatch, "release/1.0.0-notes", PAGE, date="") == PAGE
